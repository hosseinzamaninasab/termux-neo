#!/data/data/com.termux/files/usr/bin/bash

# ==========================================================
# Termux Neo - UI Engine
# ==========================================================

# Dashboard rows
declare -a UI_ROWS

# Status bar items
declare -a UI_STATUS

# Dashboard title
UI_TITLE=""
UI_WIDTH=0

# ----------------------------------------------------------
# Initialize UI Engine
# ----------------------------------------------------------

ui_init() {
    UI_ROWS=()
    UI_STATUS=()
    UI_TITLE=""

    UI_WIDTH=$(tput cols)
}

# ----------------------------------------------------------
# Set Dashboard Title
# ----------------------------------------------------------

ui_title() {
    UI_TITLE="$1"
}

# ----------------------------------------------------------
# Add Dashboard Row
# ----------------------------------------------------------

ui_add_row() {
    UI_ROWS+=("$1|$2")
}

# ----------------------------------------------------------
# Add Status Item
# ----------------------------------------------------------

ui_add_status() {
    UI_STATUS+=("$1")
}

# ----------------------------------------------------------
# Render Dashboard
# ----------------------------------------------------------

# ----------------------------------------------------------
# Render Top Border
# ----------------------------------------------------------

ui_render_top() {
    echo "╔$(printf '═%.0s' $(seq 1 "$UI_WIDTH"))╗"
}

# ----------------------------------------------------------
# Render Title
# ----------------------------------------------------------

ui_render_title() {

    printf "║%*s%s%*s║\n" \
        $(((UI_WIDTH-${#UI_TITLE})/2)) "" \
        "$UI_TITLE" \
        $(((UI_WIDTH-${#UI_TITLE})/2)) ""
}

# ----------------------------------------------------------
# Render Separator
# ----------------------------------------------------------

ui_render_separator() {
    echo "║$(printf '─%.0s' $(seq 1 "$UI_WIDTH"))║"
}

# ----------------------------------------------------------
# Render Rows
# ----------------------------------------------------------

ui_render_rows() {

    for row in "${UI_ROWS[@]}"
    do
        IFS="|" read -r key value <<< "$row"

        printf "║  %-9s %-25s║\n" \
            "$key" \
            "$value"
    done

}

# ----------------------------------------------------------
# Render Bottom Border
# ----------------------------------------------------------

ui_render_bottom() {
    echo "╚$(printf '═%.0s' $(seq 1 "$UI_WIDTH"))╝"
}

# ----------------------------------------------------------
# Render Dashboard
# ----------------------------------------------------------

ui_render() {

    ui_render_top

    ui_render_title

    ui_render_separator

    ui_render_rows

    ui_render_bottom

}
